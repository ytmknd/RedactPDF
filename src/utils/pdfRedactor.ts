import { PDFDocument, rgb } from "pdf-lib";
import type { PDFDocumentProxy } from "pdfjs-dist/legacy/build/pdf.mjs";
import type { MasksByPage } from "../types/pdf";

type GenerateParams = {
  sourcePdf: PDFDocumentProxy;
  masksByPage: MasksByPage;
  outputScale?: number;
  onProgress?: (donePages: number, totalPages: number) => void;
};

function canvasToPngDataUrl(canvas: HTMLCanvasElement): string {
  return canvas.toDataURL("image/png");
}

export async function generateSecureMaskedPdf(params: GenerateParams): Promise<Uint8Array> {
  const { sourcePdf, masksByPage, outputScale = 2, onProgress } = params;
  const totalPages = sourcePdf.numPages;
  const outputPdf = await PDFDocument.create();

  outputPdf.setTitle("RedactPDF Output");
  outputPdf.setSubject("Securely redacted PDF generated by RedactPDF");
  outputPdf.setProducer("RedactPDF");
  outputPdf.setCreator("RedactPDF");
  outputPdf.setAuthor("");
  outputPdf.setKeywords([]);
  outputPdf.setLanguage("ja");

  for (let pageIndex = 0; pageIndex < totalPages; pageIndex += 1) {
    const page = await sourcePdf.getPage(pageIndex + 1);
    const baseViewport = page.getViewport({ scale: 1 });
    const renderViewport = page.getViewport({ scale: outputScale });

    const outputCanvas = document.createElement("canvas");
    outputCanvas.width = Math.floor(renderViewport.width);
    outputCanvas.height = Math.floor(renderViewport.height);

    const ctx = outputCanvas.getContext("2d");
    if (!ctx) {
      throw new Error("出力用Canvasの初期化に失敗しました。");
    }

    ctx.save();
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, outputCanvas.width, outputCanvas.height);
    ctx.restore();

    await page
      .render({
        canvas: outputCanvas,
        canvasContext: ctx,
        viewport: renderViewport,
        background: "#ffffff",
      })
      .promise;

    const pageMasks = masksByPage[pageIndex] ?? [];
    ctx.save();
    ctx.globalAlpha = 1;
    ctx.fillStyle = "#000000";

    for (const mask of pageMasks) {
      const x = Math.max(0, Math.floor(mask.x * outputCanvas.width));
      const y = Math.max(0, Math.floor(mask.y * outputCanvas.height));
      const width = Math.min(outputCanvas.width - x, Math.ceil(mask.width * outputCanvas.width));
      const height = Math.min(outputCanvas.height - y, Math.ceil(mask.height * outputCanvas.height));

      if (width > 0 && height > 0) {
        ctx.fillRect(x, y, width, height);
      }
    }

    ctx.restore();

    const pngDataUrl = canvasToPngDataUrl(outputCanvas);
    const pngImage = await outputPdf.embedPng(pngDataUrl);

    const outPage = outputPdf.addPage([baseViewport.width, baseViewport.height]);
    outPage.drawRectangle({
      x: 0,
      y: 0,
      width: baseViewport.width,
      height: baseViewport.height,
      color: rgb(1, 1, 1),
    });
    outPage.drawImage(pngImage, {
      x: 0,
      y: 0,
      width: baseViewport.width,
      height: baseViewport.height,
      opacity: 1,
    });

    onProgress?.(pageIndex + 1, totalPages);
  }

  return outputPdf.save({
    useObjectStreams: true,
    addDefaultPage: false,
    updateFieldAppearances: false,
  });
}
